/**
 * For radian conversion
 *
 * @constant
 * @type    {number}
 */
export const PI180: number = Math.PI / 180;

/**
 * Twice of PI
 *
 * @constant
 * @type {number}
 */
export const PI2: number = Math.PI * 2;

/**
 * Half of PI
 *
 * @constant
 * @type {number}
 */
export const HALFPI: number = Math.PI / 2;
